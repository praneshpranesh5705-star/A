-- Soil Field Monitor — Supabase schema
-- Run this once in the Supabase SQL editor for your project.

create table if not exists readings (
  id bigint generated by default as identity primary key,
  soil_moisture numeric not null,   -- percent, 0-100
  temperature numeric not null,     -- degrees Celsius
  created_at timestamptz not null default now()
);

alter table readings enable row level security;

-- The ESP32 uses the anon key to insert new readings
create policy "Allow insert from device"
  on readings for insert
  to anon
  with check (true);

-- The dashboard uses the anon key to read readings
create policy "Allow public read"
  on readings for select
  to anon
  using (true);

