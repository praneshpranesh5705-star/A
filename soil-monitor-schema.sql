-- ------------------------------------------------------------
-- AUTOMATIC IRRIGATION
-- The ESP32 writes the current pump state and irrigation events.
-- The dashboard can read these rows for pump status/history.
-- ------------------------------------------------------------
alter table readings add column if not exists device_id text default 'ESP32-Field-01';

create table if not exists irrigation_events (
  id bigint generated by default as identity primary key,
  device_id text not null default 'ESP32-Field-01',
  moisture_before numeric,
  moisture_after numeric,
  duration_seconds integer not null,
  trigger text not null, -- 'automatic' or 'manual'
  created_at timestamptz not null default now()
);

alter table irrigation_events enable row level security;

create policy "Allow irrigation insert from device"
  on irrigation_events for insert
  to anon
  with check (true);

create policy "Allow irrigation public read"
  on irrigation_events for select
  to anon
  using (true);
